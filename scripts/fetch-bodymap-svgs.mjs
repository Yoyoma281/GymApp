// Bundle wger's muscle-highlight SVGs into the app.
//
// wger serves these without CORS headers, so fetching them at runtime
// fails in browsers; bundling also makes body maps work offline. The
// two body silhouettes are large (~300-400KB) and get minified here;
// the per-muscle overlays are a few KB each.
//
// Usage: node scripts/fetch-bodymap-svgs.mjs
// Output: src/data/generated/bodyMapSvgs.ts

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const GEN_DIR = path.join(here, '..', 'src', 'data', 'generated');
const BASE = 'https://wger.de/static/images/muscles';
const OUT = path.join(GEN_DIR, 'bodyMapSvgs.ts');

// Which muscle layers are actually referenced by the catalog
const details = JSON.parse(fs.readFileSync(path.join(GEN_DIR, 'exercise-details.json'), 'utf8'));
const main = new Set();
const secondary = new Set();
for (const d of Object.values(details)) {
  for (const m of d.muscleIds ?? []) main.add(m.id);
  for (const m of d.secondaryMuscleIds ?? []) secondary.add(m.id);
}

// Strip XML prolog/comments/metadata and collapse whitespace — these
// Inkscape exports carry a lot of editor cruft.
//
// They also declare a fixed width/height (200x369) with NO viewBox, so
// rendering them at 100% of a smaller container crops the artwork
// instead of scaling it. Convert the intrinsic size into a viewBox and
// let the container drive the size.
function minify(svg) {
  const cleaned = svg
    .replace(/<\?xml[^>]*\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<metadata[\s\S]*?<\/metadata>/g, '')
    .replace(/<sodipodi:namedview[\s\S]*?(\/>|<\/sodipodi:namedview>)/g, '')
    .replace(/\s+/g, ' ')
    .replace(/> </g, '><')
    .trim();

  const open = cleaned.match(/<svg\b[^>]*>/);
  if (!open) return cleaned;
  let tag = open[0];
  if (!/viewBox=/.test(tag)) {
    const w = parseFloat(tag.match(/\bwidth="([\d.]+)/)?.[1] ?? '200');
    const h = parseFloat(tag.match(/\bheight="([\d.]+)/)?.[1] ?? '369');
    tag = tag.replace(/<svg\b/, `<svg viewBox="0 0 ${w} ${h}" preserveAspectRatio="xMidYMid meet"`);
  }
  // Drop the fixed pixel size so width/height props take effect.
  tag = tag.replace(/\s(width|height)="[^"]*"/g, '');
  return cleaned.replace(open[0], tag);
}

async function get(pathname) {
  const res = await fetch(`${BASE}/${pathname}`);
  if (!res.ok) throw new Error(`${pathname}: ${res.status}`);
  return minify(await res.text());
}

const body = {
  front: await get('muscular_system_front.svg'),
  back: await get('muscular_system_back.svg'),
};
const mainSvgs = {};
for (const id of [...main].sort((a, b) => a - b)) {
  mainSvgs[id] = await get(`main/muscle-${id}.svg`);
}
const secondarySvgs = {};
for (const id of [...secondary].sort((a, b) => a - b)) {
  secondarySvgs[id] = await get(`secondary/muscle-${id}.svg`);
}

const out = [
  '// AUTO-GENERATED by scripts/fetch-bodymap-svgs.mjs — do not edit by hand.',
  '// Muscle diagrams from wger.de (CC-BY-SA), bundled because wger serves',
  '// them without CORS headers and so body maps also work offline.',
  '',
  `export const bodySvg: Record<'front' | 'back', string> = ${JSON.stringify(body)};`,
  '',
  `export const mainMuscleSvg: Record<number, string> = ${JSON.stringify(mainSvgs)};`,
  '',
  `export const secondaryMuscleSvg: Record<number, string> = ${JSON.stringify(secondarySvgs)};`,
  '',
];
fs.writeFileSync(OUT, out.join('\n'));
const kb = (fs.statSync(OUT).size / 1024).toFixed(0);
console.log(`wrote bodyMapSvgs.ts (${kb} KB): 2 silhouettes, ${Object.keys(mainSvgs).length} main, ${Object.keys(secondarySvgs).length} secondary`);
